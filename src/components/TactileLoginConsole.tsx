import {
  useState,
  useRef,
  useEffect,
  useCallback,
  type CSSProperties,
  type ReactNode,
} from "react";
import baseConsoleWebp from "../assets/tactile-login/base_console.webp";
import headerBrandCleanWebp from "../assets/tactile-login/header_brand_clean.webp";
import screenEmailTextCleanWebp from "../assets/tactile-login/screen_email_text_clean.webp";
import screenCodeTextCleanWebp from "../assets/tactile-login/screen_code_text_clean.webp";
import btnSendPressedWebp from "../assets/tactile-login/btn_send_pressed.webp";
import btnLoginPressedWebp from "../assets/tactile-login/btn_login_pressed.webp";
import btnGuestPressedWebp from "../assets/tactile-login/btn_guest_pressed.webp";
import halfCircleSvg from "../assets/tactile-login/half_circle.svg";
import {
  PixelEnvelopeIcon,
  PixelKeyIcon,
} from "./tactile/PixelFieldIcons";
import { ensureFusionPixelFont } from "../lib/fusionPixelFont";

export type LoginMethod = "code" | "password";

/**
 * 顶部金属铭牌品牌默认配置（左上角圆角凹槽 Logo 资源位 + 主副标题）
 * - 后续接入 Logo 时：直接 import 图标资源并赋给 `logoSrc`（如 `logoSrc: myLogoSvg`），
 *   或通过组件 props 传入 `brandLogo` 即可自动在左侧金属凹槽内居中渲染蚀刻风格图标。
 */
export const HEADER_BRAND_CONFIG: {
  /** 左上角圆角凹槽内的 Logo 资源路径（留空为 null，仅展示干净凹槽底座） */
  logoSrc: string | null;
  logoAlt: string;
  title: string;
  subtitle: string;
} = {
  logoSrc: halfCircleSvg,
  logoAlt: "TERMINAL 0932",
  title: "TERMINAL 0932",
  subtitle: "Generated by Gemini4 Argon",
};

export interface TactileLoginConsoleProps {
  method: LoginMethod;
  onMethodChange: (method: LoginMethod) => void;
  email: string;
  onEmailChange: (email: string) => void;
  code: string;
  onCodeChange: (code: string) => void;
  password: string;
  onPasswordChange: (password: string) => void;
  onSendCode: () => void;
  onSubmit: (e: React.FormEvent) => void;
  onGuestLogin: () => void;
  loading: boolean;
  guestLoading: boolean;
  sendingCode: boolean;
  cooldown: number;
  codeSent: boolean;
  error: string;
  onErrorClear?: () => void;
  devCode: string | null;
  /** 选中态点阵白底外围辉光强度 */
  tabPillGlow?: number;
  /** 左上角凹槽 Logo 资源位（可传图片 URL 或自定义 React 节点；默认读取 HEADER_BRAND_CONFIG.logoSrc） */
  brandLogo?: string | ReactNode | null;
  /** 顶部主标题（默认 "Hrak"） */
  brandTitle?: string;
  /** 顶部副标题（默认 "Hrak login console"） */
  brandSubtitle?: string;
}

/**
 * 实物图层交互式登录台（Tactile Hardware Login Console）
 * 基于 1024×1024 物理摄影底图 + 状态切图图层叠加（火山引擎 AI 抠图去背 + 亚像素羽化切图）
 */
export function TactileLoginConsole({
  method,
  onMethodChange,
  email,
  onEmailChange,
  code,
  onCodeChange,
  password,
  onPasswordChange,
  onSendCode,
  onSubmit,
  onGuestLogin,
  loading,
  guestLoading,
  sendingCode,
  cooldown,
  error,
  onErrorClear,
  devCode: _devCode,
  tabPillGlow = 0.9,
  brandLogo = HEADER_BRAND_CONFIG.logoSrc,
  brandTitle = HEADER_BRAND_CONFIG.title,
  brandSubtitle = HEADER_BRAND_CONFIG.subtitle,
}: TactileLoginConsoleProps) {
  const [emailFocused, setEmailFocused] = useState(false);
  const [codeFocused, setCodeFocused] = useState(false);
  const [passwordFocused, setPasswordFocused] = useState(false);

  // 机械按键按下状态（含短按 180ms 物理回弹保持，确保快速点击也能清晰看到按键下陷切图）
  const [sendPressed, setSendPressed] = useState(false);
  const [loginPressed, setLoginPressed] = useState(false);
  const [guestPressed, setGuestPressed] = useState(false);

  const sendTimerRef = useRef<number | null>(null);
  const loginTimerRef = useRef<number | null>(null);
  const guestTimerRef = useRef<number | null>(null);

  useEffect(() => {
    void ensureFusionPixelFont();
    return () => {
      if (sendTimerRef.current) window.clearTimeout(sendTimerRef.current);
      if (loginTimerRef.current) window.clearTimeout(loginTimerRef.current);
      if (guestTimerRef.current) window.clearTimeout(guestTimerRef.current);
    };
  }, []);

  const triggerTactileHold = useCallback(
    (
      setter: React.Dispatch<React.SetStateAction<boolean>>,
      timerRef: React.MutableRefObject<number | null>,
      durationMs = 190
    ) => {
      if (timerRef.current) window.clearTimeout(timerRef.current);
      setter(true);
      timerRef.current = window.setTimeout(() => {
        setter(false);
        timerRef.current = null;
      }, durationMs);
    },
    []
  );

  // 错误归类分流：判断当前是邮箱报错还是验证码/密码报错
  const isEmailError = Boolean(
    error &&
      (error.includes("邮箱") ||
        (!email.trim() && !error.includes("验证码") && !error.includes("密码")))
  );
  const isCodeOrPasswordError = Boolean(error && !isEmailError);

  // 始终盖住底图自带的平滑占位字与图标，改由像素点阵 UI 覆层绘制
  const showEmailCleanSlice = true;
  const showCodeCleanSlice = true;

  const isSendDepressed = sendPressed || sendingCode;
  const isLoginDepressed = loginPressed || loading;
  const isGuestDepressed = guestPressed || guestLoading;

  return (
    <div className="relative flex w-full flex-col items-center select-none">
      {/* 1:1 物理硬件交互主舞台（严格对齐 1024×1024 坐标系，光学中心对准金属机身） */}
      <form
        noValidate
        data-tactile-console-form="true"
        onSubmit={onSubmit}
        style={{ containerType: "inline-size" }}
        className="relative aspect-square w-full max-w-[560px] lg:max-w-[640px] xl:max-w-[680px] lg:translate-y-[4.5%] lg:translate-x-[3%]"
      >
        {/* Layer 0: 火山引擎 AI 抠图去背后的拉丝金属机身 + 紫色螺旋线缆底图 */}
        <img
          src={baseConsoleWebp}
          alt={`${brandTitle} Hardware Login Console`}
          draggable={false}
          className="pointer-events-none absolute inset-0 h-full w-full object-contain drop-shadow-[22px_28px_36px_rgba(0,0,0,0.82)]"
        />

        {/* Layer 0.2: 顶部铭牌干净拉丝金属补丁（无损抹除底图自带的月亮图标与旧文案，保留左侧圆角凹槽底座与竖向分割刻线 |） */}
        <img
          src={headerBrandCleanWebp}
          alt=""
          aria-hidden="true"
          draggable={false}
          style={{
            left: "21.094%",
            top: "16.797%",
            width: "41.211%",
            height: "8.008%",
          }}
          className="pointer-events-none absolute object-fill"
        />

        {/* Layer 0.3: 顶部金属铭牌 —— 左侧圆角凹槽 Logo 预留资源位 + 右侧蚀刻主/副标题 */}
        {/* 1) 左上角圆角凹槽 Logo 资源位（精确定位到凹槽物理中心：X=251px / Y=215.25px，四边间距绝对均等） */}
        <div
          data-tactile-brand-logo-slot="true"
          style={{
            left: "24.512%",
            top: "21.021%",
            width: "6.25%",
            height: "6.25%",
            transform: "translate(-50%, -50%)",
          }}
          className="pointer-events-none absolute z-10 flex items-center justify-center overflow-hidden rounded-[22%]"
          aria-hidden={!brandLogo}
        >
          {typeof brandLogo === "string" && brandLogo ? (
            <img
              src={brandLogo}
              alt={HEADER_BRAND_CONFIG.logoAlt}
              draggable={false}
              style={{
                filter:
                  "brightness(0) invert(0.15) sepia(0.08) drop-shadow(0 1px 0 rgba(255,255,255,0.28))",
              }}
              className="h-[62.5%] w-[62.5%] object-contain opacity-90"
            />
          ) : (
            brandLogo ?? null
          )}
        </div>

        {/* 2) 竖线右侧：原版金属蚀刻斜体主标题 & 副标题（垂直居中对齐竖线 | 与 Logo 中心线 Y=215.25px，紧凑行距） */}
        <div
          style={{
            left: "33.691%",
            top: "21.021%",
            width: "34%",
            transform: "translateY(-50%)",
            gap: "0.38cqw",
          }}
          className="pointer-events-none absolute z-10 flex flex-col justify-center select-none"
        >
          <div
            style={{
              fontFamily:
                '"Inter", "Segoe UI", -apple-system, BlinkMacSystemFont, sans-serif',
              fontStyle: "italic",
              fontWeight: 700,
              fontSize: "2.95cqw",
              lineHeight: 0.95,
              letterSpacing: "-0.015em",
              color: "#282624",
              textShadow:
                "0 1px 0 rgba(255, 255, 255, 0.30), 0 -0.5px 0 rgba(0, 0, 0, 0.42)",
            }}
            className="truncate"
          >
            {brandTitle}
          </div>
          <div
            style={{
              fontFamily:
                '"Inter", "Segoe UI", "PingFang SC", "Microsoft YaHei", sans-serif',
              fontWeight: 500,
              fontSize: "1.72cqw",
              lineHeight: 1.02,
              letterSpacing: "0.02em",
              color: "#3b3938",
              textShadow:
                "0 1px 0 rgba(255, 255, 255, 0.24), 0 -0.5px 0 rgba(0, 0, 0, 0.25)",
            }}
            className="truncate"
          >
            {brandSubtitle}
          </div>
        </div>

        {/* Layer 0.5: 右上角绿色 LED 状态灯呼吸闪烁增强层（精准锚定 1024×1024 物理灯珠中心 705.3, 202.5，Screen 滤色屏幕混合模式，正常亮 -> 更亮 -> 正常亮） */}
        <div
          style={{
            left: "68.88%",
            top: "19.78%",
            width: "2.15%",
            height: "2.15%",
            transform: "translate(-50%, -50%)",
            mixBlendMode: "screen",
          }}
          className="tactile-led-glow pointer-events-none absolute z-10 flex items-center justify-center mix-blend-screen"
          aria-hidden="true"
        >
          {/* 外圈微光晕（向四周金属边框微弱漫反射翡翠荧光） */}
          <div className="absolute inset-[-40%] rounded-full bg-[#22c55e]/60 blur-[3px]" />
          {/* 聚光透镜灯珠主体（精准贴合 14~18px 物理灯珠体） */}
          <div className="absolute inset-0 rounded-full bg-[#4ade80]/90 blur-[1px]" />
          {/* 核心晶片高光白绿发光点 */}
          <div className="relative h-[55%] w-[55%] rounded-full bg-gradient-to-tr from-[#4ade80] via-[#bbf7d0] to-[#ffffff] shadow-[0_0_4px_1px_rgba(255,255,255,0.9)]" />
        </div>

        {/* Layer 1: 顶部登录方式切换 UI（纯 UI 矢量实现，圆角与底图跑道凹槽精密同心对齐，支持丝滑机械滑块物理动画） */}
        <div
          style={{
            left: "19.922%",
            top: "27.441%",
            width: "55.176%",
            height: "7.715%",
          }}
          className="absolute z-20 flex select-none items-center overflow-visible"
        >
          {/* 金属滑轨深邃内凹槽容器（圆角同心贴合底图凹槽；overflow 放开以免裁切辉光） */}
          <div className="relative flex h-full w-full items-center overflow-visible rounded-[14px] sm:rounded-[15px] md:rounded-[16px]">
            {/* 选中态像素白底指示块（点阵 + 可调辉光） */}
            <div
              className={`absolute top-[2.5px] bottom-[2.5px] left-[2.5px] z-[1] overflow-visible sm:top-[3px] sm:bottom-[3px] sm:left-[3px] w-[calc(50%-2.5px)] sm:w-[calc(50%-3px)] transition-transform duration-200 ease-[cubic-bezier(0.16,1,0.3,1)] pointer-events-none ${
                method === "password" ? "translate-x-full" : "translate-x-0"
              }`}
              style={
                {
                  "--tab-pill-glow": String(Math.max(0, tabPillGlow)),
                } as CSSProperties
              }
            >
              {/* 外层辉光层（box-shadow，受 --tab-pill-glow 控制） */}
              <div
                aria-hidden
                className="tactile-pixel-tab-glow absolute inset-[2px]"
                style={
                  {
                    "--tab-pill-glow": String(Math.max(0, tabPillGlow)),
                    opacity: tabPillGlow <= 0 ? 0 : 1,
                  } as CSSProperties
                }
              />
              {/* 点阵白底：像素间留空隙，无描边 */}
              <div className="tactile-pixel-tab-pill relative z-[1] h-full w-full" />
            </div>

            {/* Tab 1: 验证码登录（本地 Fusion Pixel；选中时字号放大） */}
            <button
              type="button"
              role="tab"
              aria-selected={method === "code"}
              onClick={() => onMethodChange("code")}
              className={`tactile-pixel-text relative z-10 flex h-full w-1/2 cursor-pointer items-center justify-center rounded-[11px] sm:rounded-[12px] md:rounded-[13px] outline-none ${
                method === "code"
                  ? "tactile-pixel-text-selected text-[#1c1729]"
                  : "text-white/70"
              }`}
            >
              验证码登录
            </button>

            {/* Tab 2: 密码登录（本地 Fusion Pixel；选中时字号放大） */}
            <button
              type="button"
              role="tab"
              aria-selected={method === "password"}
              onClick={() => onMethodChange("password")}
              className={`tactile-pixel-text relative z-10 flex h-full w-1/2 cursor-pointer items-center justify-center rounded-[11px] sm:rounded-[12px] md:rounded-[13px] outline-none ${
                method === "password"
                  ? "tactile-pixel-text-selected text-[#1c1729]"
                  : "text-white/70"
              }`}
            >
              密码登录
            </button>
          </div>
        </div>

        {/* Layer 2: 企业邮箱空白屏幕切图（聚焦或输入文字时覆盖「企业邮箱」占位字，保留左侧信封图标） */}
        <img
          src={screenEmailTextCleanWebp}
          alt=""
          aria-hidden="true"
          draggable={false}
          style={{
            left: "25.586%",
            top: "37.305%",
            width: "49.219%",
            height: "7.031%",
          }}
          className={`pointer-events-none absolute object-fill transition-opacity duration-100 ${
            showEmailCleanSlice ? "opacity-100" : "opacity-0"
          }`}
        />

        {/* Layer 3: 验证码 / 密码空白屏幕切图（聚焦、输入或切换至密码模式时覆盖「6 位验证码」占位字，保留左侧钥匙图标） */}
        <img
          src={screenCodeTextCleanWebp}
          alt=""
          aria-hidden="true"
          draggable={false}
          style={{
            left: "25.586%",
            top: "46.289%",
            width: "30.664%",
            height: "6.641%",
          }}
          className={`pointer-events-none absolute object-fill transition-opacity duration-100 ${
            showCodeCleanSlice ? "opacity-100" : "opacity-0"
          }`}
        />

        {/* Layer 4: 右侧紫色「获取验证码」机械按键被按下状态切图 */}
        <img
          src={btnSendPressedWebp}
          alt=""
          aria-hidden="true"
          draggable={false}
          style={{
            left: "58.789%",
            top: "45.605%",
            width: "17.090%",
            height: "9.277%",
          }}
          className={`pointer-events-none absolute object-fill transition-opacity duration-75 ${
            isSendDepressed ? "opacity-100" : "opacity-0"
          }`}
        />

        {/* Layer 5: 底部宽幅米白「登 录」主机械按键被按下状态切图 */}
        <img
          src={btnLoginPressedWebp}
          alt=""
          aria-hidden="true"
          draggable={false}
          style={{
            left: "19.141%",
            top: "55.371%",
            width: "39.258%",
            height: "10.840%",
          }}
          className={`pointer-events-none absolute object-fill transition-opacity duration-75 ${
            isLoginDepressed ? "opacity-100" : "opacity-0"
          }`}
        />

        {/* Layer 6: 右下角深灰「游客」机械按键被按下状态切图 */}
        <img
          src={btnGuestPressedWebp}
          alt=""
          aria-hidden="true"
          draggable={false}
          style={{
            left: "58.887%",
            top: "55.566%",
            width: "16.895%",
            height: "10.645%",
          }}
          className={`pointer-events-none absolute object-fill transition-opacity duration-75 ${
            isGuestDepressed ? "opacity-100" : "opacity-0"
          }`}
        />

        {/* ==================== 交互热区与真实 OLED 输入层 ==================== */}

        {/* 1. 企业邮箱 OLED 屏幕输入框 */}
        <div
          style={{
            left: "19.8%",
            top: "37.4%",
            width: "55.4%",
            height: "7.0%",
          }}
          className="absolute z-20 flex items-center"
        >
          {/* 遮盖底图平滑信封图标 + 像素点阵信封 */}
          <div
            className="pointer-events-none absolute left-[2.8%] top-1/2 z-10 flex h-[58%] w-[8.2%] -translate-y-1/2 items-center justify-center text-[#a7adb8]"
            aria-hidden
          >
            <div className="absolute inset-[-22%_-18%] rounded-[3px] bg-[#0b0b0e]" />
            <PixelEnvelopeIcon className="relative h-[82%] w-auto text-[#a7adb8]" />
          </div>

          {isEmailError && !email ? (
            <span
              style={{ left: "13.2%" }}
              className="tactile-pixel-text pointer-events-none absolute z-[11] max-w-[82%] truncate text-red-400"
            >
              {error}
            </span>
          ) : (
            !emailFocused &&
            email.length === 0 && (
              <span
                style={{ left: "13.2%" }}
                className="tactile-pixel-text pointer-events-none absolute z-[11] select-none text-[#8e929f]"
              >
                企业邮箱
              </span>
            )
          )}
          <input
            type="email"
            aria-label="企业邮箱"
            value={email}
            autoComplete="username email"
            onFocus={() => {
              setEmailFocused(true);
              if (isEmailError) onErrorClear?.();
            }}
            onBlur={() => setEmailFocused(false)}
            onChange={(e) => {
              onEmailChange(e.target.value);
              if (error) onErrorClear?.();
            }}
            style={{
              paddingLeft: "13.2%",
              paddingRight: "4%",
              WebkitTextFillColor: "#e6e9f2",
              transition: "background-color 999999s ease-in-out 0s",
            }}
            className="tactile-oled-input tactile-pixel-text h-full w-full rounded-[20px] border-0 bg-transparent text-[#e6e9f2] caret-[#a78bfa] outline-none selection:bg-violet-500/35"
          />
        </div>

        {/* 2. 6 位验证码 / 密码 OLED 屏幕输入框 */}
        <div
          style={{
            left: "19.8%",
            top: "46.2%",
            width: "36.8%",
            height: "6.8%",
          }}
          className="absolute z-20 flex items-center"
        >
          {/* 遮盖底图平滑钥匙图标 + 像素点阵钥匙 */}
          <div
            className="pointer-events-none absolute left-[4.2%] top-1/2 z-10 flex h-[58%] w-[12.5%] -translate-y-1/2 items-center justify-center text-[#a7adb8]"
            aria-hidden
          >
            <div className="absolute inset-[-22%_-14%] rounded-[3px] bg-[#0b0b0e]" />
            <PixelKeyIcon className="relative h-[82%] w-auto text-[#a7adb8]" />
          </div>

          {method === "password" ? (
            <>
              {isCodeOrPasswordError ? (
                <span
                  style={{ left: "20.5%" }}
                  className="tactile-pixel-text pointer-events-none absolute z-[11] max-w-[75%] truncate text-red-400"
                >
                  {error}
                </span>
              ) : (
                !passwordFocused &&
                password.length === 0 && (
                  <span
                    style={{ left: "20.5%" }}
                    className="tactile-pixel-text pointer-events-none absolute z-[11] select-none text-[#8e929f]"
                  >
                    请输入密码
                  </span>
                )
              )}
              <input
                type="password"
                aria-label="密码"
                value={password}
                autoComplete="current-password"
                onFocus={() => {
                  setPasswordFocused(true);
                  if (isCodeOrPasswordError) onErrorClear?.();
                }}
                onBlur={() => setPasswordFocused(false)}
                onChange={(e) => {
                  onPasswordChange(e.target.value);
                  if (error) onErrorClear?.();
                }}
                style={{
                  paddingLeft: "20.5%",
                  paddingRight: "5%",
                  WebkitTextFillColor: "#e6e9f2",
                  transition: "background-color 999999s ease-in-out 0s",
                  letterSpacing: "0.08em",
                }}
                className="tactile-oled-input tactile-pixel-text h-full w-full rounded-[20px] border-0 bg-transparent text-[#e6e9f2] caret-[#a78bfa] outline-none selection:bg-violet-500/35"
              />
            </>
          ) : (
            <>
              {isCodeOrPasswordError ? (
                <span
                  style={{ left: "20.5%" }}
                  className="tactile-pixel-text pointer-events-none absolute z-[11] max-w-[75%] truncate text-red-400"
                >
                  {error}
                </span>
              ) : (
                !codeFocused &&
                code.length === 0 && (
                  <span
                    style={{ left: "20.5%" }}
                    className="tactile-pixel-text pointer-events-none absolute z-[11] select-none text-[#8e929f]"
                  >
                    输入验证码
                  </span>
                )
              )}
              <input
                type="text"
                inputMode="numeric"
                aria-label="输入验证码"
                maxLength={6}
                value={code}
                autoComplete="one-time-code"
                onFocus={() => {
                  setCodeFocused(true);
                  if (isCodeOrPasswordError) onErrorClear?.();
                }}
                onBlur={() => setCodeFocused(false)}
                onChange={(e) => {
                  onCodeChange(e.target.value.replace(/\D/g, ""));
                  if (error) onErrorClear?.();
                }}
                style={{
                  paddingLeft: "20.5%",
                  paddingRight: "5%",
                  WebkitTextFillColor: "#e6e9f2",
                  transition: "background-color 999999s ease-in-out 0s",
                  letterSpacing: "0.14em",
                }}
                className="tactile-oled-input tactile-pixel-text h-full w-full rounded-[20px] border-0 bg-transparent text-[#e6e9f2] caret-[#a78bfa] outline-none selection:bg-violet-500/35"
              />
            </>
          )}
        </div>

        {/* 3. 右侧紫色「获取验证码」机械按键热区 */}
        <button
          type="button"
          aria-label="获取验证码"
          disabled={cooldown > 0 || sendingCode}
          onPointerDown={() => {
            if (cooldown <= 0 && !sendingCode) setSendPressed(true);
          }}
          onPointerUp={() =>
            triggerTactileHold(setSendPressed, sendTimerRef, 180)
          }
          onPointerLeave={() => setSendPressed(false)}
          onClick={() => {
            triggerTactileHold(setSendPressed, sendTimerRef, 200);
            onSendCode();
          }}
          style={{
            left: "57.8%",
            top: "45.2%",
            width: "17.8%",
            height: "8.2%",
          }}
          className="group absolute z-20 flex cursor-pointer items-center justify-center rounded-[16px] bg-transparent focus:outline-none disabled:cursor-not-allowed"
        >
          {/* 倒计时状态覆层（当处于 60s 冷却或发送中时，在紫色键帽中心显示倒计时） */}
          {(cooldown > 0 || sendingCode) && (
            <span
              className={`flex h-[74%] w-[86%] items-center justify-center rounded-[10px] bg-[#7c6398]/95 font-mono text-xs font-bold tracking-wider text-[#1d1626] shadow-inner transition-transform duration-75 ${
                isSendDepressed ? "translate-y-[1.5px]" : ""
              }`}
            >
              {sendingCode ? "..." : `${cooldown}s`}
            </span>
          )}
        </button>

        {/* 6. 底部宽幅米白「登 录」主机械按键热区 */}
        <button
          type="submit"
          aria-label="登录"
          disabled={loading}
          onPointerDown={() => {
            if (!loading) setLoginPressed(true);
          }}
          onPointerUp={() =>
            triggerTactileHold(setLoginPressed, loginTimerRef, 180)
          }
          onPointerLeave={() => setLoginPressed(false)}
          onClick={() =>
            triggerTactileHold(setLoginPressed, loginTimerRef, 200)
          }
          style={{
            left: "19.5%",
            top: "54.8%",
            width: "37.2%",
            height: "10.2%",
          }}
          className="absolute z-20 cursor-pointer rounded-[18px] bg-transparent focus:outline-none disabled:cursor-wait"
        />

        {/* 7. 右下角深灰「游客」机械按键热区 */}
        <button
          type="button"
          aria-label="游客登录"
          disabled={guestLoading}
          onPointerDown={() => {
            if (!guestLoading) setGuestPressed(true);
          }}
          onPointerUp={() =>
            triggerTactileHold(setGuestPressed, guestTimerRef, 180)
          }
          onPointerLeave={() => setGuestPressed(false)}
          onClick={() => {
            triggerTactileHold(setGuestPressed, guestTimerRef, 200);
            onGuestLogin();
          }}
          style={{
            left: "57.8%",
            top: "54.8%",
            width: "17.8%",
            height: "10.2%",
          }}
          className="absolute z-20 cursor-pointer rounded-[18px] bg-transparent focus:outline-none disabled:cursor-wait"
        />
      </form>
    </div>
  );
}
